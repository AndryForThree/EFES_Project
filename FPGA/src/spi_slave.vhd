library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity spi_slave is
	generic (
		DATA_WIDTH	: positive	:= 16;
		CPOL		: boolean	:= false;	-- Defines the SCLK signal level when communication is inactive
		CPHA		: boolean	:= false;	-- Defines if the sampling of MISO/MOSI is executed at leading (CPHA = 0) or trailing edge (CPHA = 1)
		LSB_FIRST	: boolean	:= false
	);
	port (
		rst_n_i			: in  std_logic;

		-- SPI Interface
		spi_sclk_i		: in  std_logic;		-- SPI Clock generated by Master
		spi_cs_n_i		: in  std_logic;		-- Device Select signal generated by master (this Slave is active when CS_n is low)
		spi_mosi_i		: in  std_logic;		-- Master Output Slave Input (basically the Serial Data Input for this slave)
		spi_miso_o		: out std_logic;		-- Master Input Slave Output (basically the Serial Data Output for this slave)

		-- TX Parallel Interface (User Logic (buffering system) -> SPI Core)
		tx_data_i		: in  std_logic_vector((DATA_WIDTH-1) downto 0);	-- Word to be transmitted 
		tx_valid_i		: in  std_logic;									-- Indicates that tx_data_i contains a valid word ready for transmission
		tx_request_o	: out std_logic;									-- Pop enable, sampled by the buffer on the TX update edge; hold tx_data_i/tx_valid_i until that edge

		-- RX Parallel Interface (SPI Core -> User Logic (buffering system))
		rx_data_o		: out std_logic_vector((DATA_WIDTH-1) downto 0);	-- Word received from SPI
		rx_valid_o		: out std_logic										-- Request the buffering system to store the received word
	);
end entity spi_slave;



architecture rtl of spi_slave is

	-- SPI Clock Edge Configuration
	constant SAMPLE_ON_RISING : boolean := (CPOL = CPHA);

	-- Serial Communication Shift Registers
	signal tx_shift_reg	: std_logic_vector(DATA_WIDTH-1 downto 0);
	signal rx_shift_reg	: std_logic_vector(DATA_WIDTH-1 downto 0);

	-- Combinatorial RX Word
	signal rx_next_word	: std_logic_vector(DATA_WIDTH-1 downto 0);

	-- Bit Counter
	signal bit_count	: natural range 0 to DATA_WIDTH-1;

	-- TX Control
	signal tx_first_bit_phase	: std_logic;
	signal tx_word_valid		: std_logic;

begin

	-- RX Word Construction
	process(all)
		variable next_word : std_logic_vector(DATA_WIDTH-1 downto 0);
	begin
		if LSB_FIRST then
			next_word := std_logic_vector(shift_right(unsigned(rx_shift_reg), 1));
			next_word(DATA_WIDTH-1) := spi_mosi_i;
		else
			next_word := std_logic_vector(shift_left(unsigned(rx_shift_reg), 1));
			next_word(0) := spi_mosi_i;
		end if;

		rx_next_word <= next_word;
	end process;

	-- RX Parallel Interface
	rx_data_o <= rx_next_word;

	rx_valid_o <= '1' when	(rst_n_i = '1') and
							(spi_cs_n_i = '0') and
							(bit_count = DATA_WIDTH-1)
					else '0';

	-- RX Sampling
	process(spi_sclk_i, spi_cs_n_i, rst_n_i)
	begin
		if (rst_n_i = '0') or (spi_cs_n_i = '1') then
			rx_shift_reg <= (others => '0');
			bit_count <= 0;
			tx_word_valid <= '0';

		elsif (SAMPLE_ON_RISING and rising_edge(spi_sclk_i)) or
			  ((not SAMPLE_ON_RISING) and falling_edge(spi_sclk_i)) then

			rx_shift_reg <= rx_next_word;

			-- Capture TX availability at the first bit of each word
			if (not CPHA) and (bit_count = 0) then
				tx_word_valid <= tx_valid_i;
			end if;

			if bit_count = DATA_WIDTH-1 then
				bit_count <= 0;
			else
				bit_count <= bit_count + 1;
			end if;
		end if;
	end process;

	-- TX Parallel Interface
	tx_request_o <= '1' when
						(rst_n_i = '1') and
						(spi_cs_n_i = '0') and
						(
							(CPHA and (bit_count = 0) and (tx_valid_i = '1')) or
							((not CPHA) and (tx_word_valid = '1') and
								((bit_count = 1) or (DATA_WIDTH = 1)))
						)
					else '0';

	-- TX Shift Register
	process(spi_sclk_i, spi_cs_n_i, rst_n_i)
	begin
		if (rst_n_i = '0') or (spi_cs_n_i = '1') then
			tx_shift_reg <= (others => '0');
			tx_first_bit_phase <= '1';

		elsif (SAMPLE_ON_RISING and falling_edge(spi_sclk_i)) or
			  ((not SAMPLE_ON_RISING) and rising_edge(spi_sclk_i)) then

			if CPHA then

				-- Load a complete word on its first update edge
				if bit_count = 0 then
					if tx_valid_i = '1' then
						tx_shift_reg <= tx_data_i;
					else
						tx_shift_reg <= (others => '0');
					end if;
				else
					if LSB_FIRST then
						tx_shift_reg <= std_logic_vector(shift_right(unsigned(tx_shift_reg), 1));
					else
						tx_shift_reg <= std_logic_vector(shift_left(unsigned(tx_shift_reg), 1));
					end if;
				end if;

			else

				-- Load the remaining bits after the first bit
				if (bit_count = 1) and (DATA_WIDTH > 1) then
					tx_first_bit_phase <= '0';

					if tx_word_valid = '1' then
						if LSB_FIRST then
							tx_shift_reg <= std_logic_vector(shift_right(unsigned(tx_data_i), 1));
						else
							tx_shift_reg <= std_logic_vector(shift_left(unsigned(tx_data_i), 1));
						end if;
					else
						tx_shift_reg <= (others => '0');
					end if;

				-- Prepare the next word after the last bit
				elsif bit_count = 0 then
					tx_first_bit_phase <= '1';

				-- Shift the remaining bits
				else
					if LSB_FIRST then
						tx_shift_reg <= std_logic_vector(shift_right(unsigned(tx_shift_reg), 1));
					else
						tx_shift_reg <= std_logic_vector(shift_left(unsigned(tx_shift_reg), 1));
					end if;
				end if;
			end if;
		end if;
	end process;

	-- MISO Output
	process(all)
	begin
		spi_miso_o <= 'Z';

		if (rst_n_i = '1') and (spi_cs_n_i = '0') then

			if (not CPHA) and (tx_first_bit_phase = '1') then
				if tx_valid_i = '1' then
					if LSB_FIRST then
						spi_miso_o <= tx_data_i(0);
					else
						spi_miso_o <= tx_data_i(DATA_WIDTH-1);
					end if;
				else
					spi_miso_o <= '0';
				end if;

			else
				if LSB_FIRST then
					spi_miso_o <= tx_shift_reg(0);
				else
					spi_miso_o <= tx_shift_reg(DATA_WIDTH-1);
				end if;
			end if;
		end if;
	end process;

end architecture rtl;
