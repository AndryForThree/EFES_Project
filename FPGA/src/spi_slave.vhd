library ieee;
use ieee.std_logic_1164.all;

entity spi_slave is
	generic (
		DATA_WIDTH	: positive	:= 16;
		CPOL		: boolean	:= false;	-- Defines the SCLK signal level when communication is inactive
		CPHA		: boolean	:= false;	-- Defines if the sampling of MISO/MOSI is executed at leading (CPHA = 0) or trailing edge (CPHA = 1)
		LSB_FIRST	: boolean	:= false
	);
	port (
		rst_n_i		: in  std_logic;

		-- SPI Interface
		spi_sclk_i	: in  std_logic;		-- SPI Clock generated by Master
		spi_cs_n_i	: in  std_logic;		-- Device Select signal generated by master (this Slave is active when CS_n is low)
		spi_mosi_i	: in  std_logic;		-- Master Output Slave Input (basically the Serial Data Input for this slave)
		spi_miso_o	: out std_logic;		-- Master Input Slave Output (basically the Serial Data Output for this slave)

		-- TX Parallel Interface (User Logic (buffering system) -> SPI Core)
		tx_data_i		: in  std_logic_vector((DATA_WIDTH-1) downto 0);	-- Word to be transmitted 
		tx_valid_i		: in  std_logic;									-- Indicates that tx_data_i contains a valid word ready for transmission
		tx_request_o	: out std_logic;									-- Indicates that the SPI Slave is accepting the current word for transmission

		-- RX Parallel Interface (SPI Core -> User Logic (buffering system))
		rx_data_o		: out std_logic_vector((DATA_WIDTH-1) downto 0);	-- Word received from SPI
		rx_valid_o		: out std_logic										-- Request the buffering system to store the received word
	);
end entity spi_slave;



architecture rtl of spi_slave is

    -- SPI Clock Edge Configuration
    constant SAMPLE_ON_RISING : boolean := (CPOL = CPHA);

    -- Serial communication Shift Registers
    signal tx_shift_reg	: std_logic_vector((DATA_WIDTH-1) downto 0);
    signal rx_shift_reg	: std_logic_vector((DATA_WIDTH-1) downto 0);

	-- Combinatorially computed RX Word (including the incoming bit)
	signal rx_next_word	: std_logic_vector(DATA_WIDTH-1 downto 0);

    -- Bit Counter
    signal bit_count	: natural range (0 to (DATA_WIDTH-1));

begin


	-- RX Word Construction
	process(all)
		variable next_word : std_logic_vector((DATA_WIDTH-1) downto 0);
	begin
		if LSB_FIRST then
			next_word := std_logic_vector(shift_right(unsigned(rx_shift_reg), 1));	-- Shift right the Shift Register
			next_word(DATA_WIDTH-1) := spi_mosi_i;									-- Set the MSB of the Shift Register to the value received from MOSI
		else
			next_word := std_logic_vector(shift_left(unsigned(rx_shift_reg), 1));	-- Shift right the Left Register
			next_word(0) := spi_mosi_i;												-- Set the LSB of the Shift Register to the value received from MOSI
		end if;

		-- Compute the next value of the RX_shift register
		rx_next_word <= next_word;
	end process;

	-- RX Parallel Interface
	rx_data_o  <= rx_next_word;
	rx_valid_o 	<=	'1'	when	(spi_cs_n_i = '0')			and 	-- The SPI Slave is enabled
								(rst_n_i = '1')				and 	-- The SPI Slave is enabled
								(bit_count = DATA_WIDTH-1)	else 	-- N-1 bits have been sampled; the last bit is available on MOSI
					'0';

	-- RX Sampling
	process(spi_sclk_i, spi_cs_n_i, rst_n_i)
	begin
		if rst_n_i = '0' or spi_cs_n_i = '1' then
			rx_shift_reg <= (others => '0');
			bit_count <= 0;

		elsif (SAMPLE_ON_RISING and rising_edge(spi_sclk_i))		or
			  (not SAMPLE_ON_RISING and falling_edge(spi_sclk_i))	then

			-- Update the shift Register with the next word computed combinatorially
			rx_shift_reg <= rx_next_word;

			-- Update the sampling counter 
			if bit_count = DATA_WIDTH-1 then
				bit_count <= 0;
			else
				bit_count <= bit_count + 1;
			end if;
		end if;
	end process;



end architecture rtl;

