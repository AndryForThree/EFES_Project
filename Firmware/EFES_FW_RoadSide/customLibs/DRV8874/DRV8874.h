#ifndef DRV8874_H_
#define DRV8874_H_

#include <stdbool.h>
#include <stdint.h>

/*
 * DRV8874 driver.
 *
 * This file contains the public interface for the Texas Instruments DRV8874 H-bridge.
 * The C implementation is in DRV8874.c.
 *
 * Because the behaviour of the DRV8874 depends on the surrounding hardware,
 * the user of this library must describe the actual circuit in the configuration defines below.
 *
 * The driver uses STM32 HAL resources configured by the hardware defines below.
 * PH/EN and IN/IN control modes are supported.
 *
 * If one of the PWM mode is configured, a duty cycle in permille (0=always logic low, 
 * 1000= always logic high) is accepted.
 *
 * Independent Half-Bridge Mode is not currently supported.
 */

// ==============================================================================================
// General constants of the DRV8874, defined by the datasheet
// ==============================================================================================

#define DRV8874_PWM_MAX_KHZ				100
#define DRV8874_AIPROPI_TYP_UA_PER_A	450	// Current Mirror ratio (Motor to IPROPI pin); 450 uA/A by default
#define DRV8874_SLEEP_DELAY_MS			1
#define DRV8874_WAKE_DELAY_MS			1

// ==============================================================================================
// Interface pin to DRV8874 mapping (can be personalized in every implementation)
// ==============================================================================================

// Pin IN1/EN and IN2/PH, based on the operating mode of the DRV7784, need a PWM output or a
// GPIO style (fixed HIGH or LOW) output. These pins are then connected to a Timer Peripheral
// set in PWM mode, which can be controlled to generate both PWM or GPIO style signals
#define DRV8874_PWM_TIMER			htim1			// Timer Peripheral used to generate the PWM
#define DRV8874_IN1_EN_CHANNEL		TIM_CHANNEL_1	// EN/IN1
#define DRV8874_IN2_PH_CHANNEL		TIM_CHANNEL_2	// PH/IN2

// Pin VREF needs a DC Voltage, which defines the Current Regulation Threshold of DRV8874
// This voltage is generated using a PWM signal generated by the microcontroller and filtered using a Low
// Pass filter with cutoff freq. << PWM Frequency. 
// In practice, another PWM Channel is used for this goal, so any voltage in the range 0V - 3V3 can be generated
// for the VREF
#define DRV8874_VREF_CHANNEL		TIM_CHANNEL_3	

// Define the GPIO Port and Pin for the PMODE selection (LOW=PH/EN, HIGH=IN/IN).
#define DRV8874_PMODE_PORT			DRV8874_PMODE_GPIO_Port
#define DRV8874_PMODE_PIN			DRV8874_PMODE_Pin

// Define the GPIO Port and Pin for the nSleep control
#define DRV8874_SLEEP_PORT			DRV8874_SLEEP_GPIO_Port
#define DRV8874_SLEEP_PIN			DRV8874_SLEEP_Pin

// Define the GPIO Port and Pin for the nFault input signal
#define DRV8874_FAULT_PORT			DRV8874_FAULT_GPIO_Port
#define DRV8874_FAULT_PIN			DRV8874_FAULT_Pin

// ADC service device and physical channel number used to acquire IPROPI.
// The service owns HAL configuration, conversion scaling and shared reference.
#define DRV8874_IPROPI_ADC			ADC_device1
#define DRV8874_IPROPI_ADC_CHANNEL	1

// ==============================================================================================
// Types and physical hardware configuration
// ==============================================================================================

// Possible configuration of the PMODE pin
// This configuration defines how the 2 Input signals are interpreted by
// the driver
typedef enum {
	DRV8874_CONTROL_PH_EN,	// PMODE tied LOW
	DRV8874_CONTROL_IN_IN,	// PMODE tied HIGH (PWM control mode)
	DRV8874_CONTROL_COUNT
} DRV8874_ControlMode;

// Possible configuration of the IMODE pin
// This configuration defines how the Driver recovers from an Overcurrent fault
// 
typedef enum {
	DRV8874_IMODE_FIXED_RETRY,	// If IMODE Pin is connected directly to GND
	DRV8874_IMODE_CBC_RETRY,	// If IMODE Pin is connected to GND through a 20 kOhm resistor
	DRV8874_IMODE_CBC_LATCH,	// If IMODE Pin is connected to GND through a 62 kOhm resistor
	DRV8874_IMODE_FIXED_LATCH,	// If IMODE Pin is left floating (Hi-Z)
	DRV8874_IMODE_COUNT
} DRV8874_CurrentMode;

// Define the Motor behaviour during the OFF period of PWM (only in IN1-IN2 mode)
typedef enum {
	DRV8874_PWM_OFF_COAST,	// Both inputs LOW during PWM OFF
	DRV8874_PWM_OFF_BRAKE,	// Both inputs HIGH during PWM OFF
	DRV8874_PWM_OFF_COUNT
} DRV8874_PwmOffMode;

// ==============================================================================================
// Fixed circuit configuration
// These configuration/parameter shouold be adjusted to match the actual HW implementation 
// ==============================================================================================

#define DRV8874_CURRENT_MODE			DRV8874_IMODE_FIXED_RETRY
#define DRV8874_IPROPI_RESISTOR_OHM		1000
#define DRV8874_VREF_FULL_SCALE_MV		3300	// VREF PWM output volatge level when HIGH

#define DRV8874_VREF_FILTER_R_OHM		10000
#define DRV8874_VREF_FILTER_C_NF		10
#define DRV8874_VREF_SETTLE_TAU_COUNT	7

// Runtime information about one DRV8874 instance.
typedef struct {
	DRV8874_ControlMode	controlMode;				// Main control mode of the DRV8874 
	DRV8874_PwmOffMode	pwmOffMode;					// Motor behaviour during the OFF period of PWM
	bool				initialized;
	bool				isAwake;
	uint32_t			vrefSettle_ms;				// Calculated from the configured RC filter
} DRV8874_Object;


// General driver handling functions
void	DRV8874_init				(DRV8874_Object *dev, DRV8874_ControlMode controlMode, DRV8874_PwmOffMode pwmOffMode, uint32_t currentLimit_mA);
void	DRV8874_close				(DRV8874_Object *dev);
void	DRV8874_wake				(DRV8874_Object *dev);
void	DRV8874_sleep				(DRV8874_Object *dev);

// DRV8874 Parameter and Mode settings
void	DRV8874_setControlMode		(DRV8874_Object *dev, DRV8874_ControlMode mode);
void	DRV8874_setCurrentLimit_mA	(DRV8874_Object *dev, uint32_t limit_mA);

// Main Motor controls 
void	DRV8874_setDutyCycle		(DRV8874_Object *dev, int16_t dutyPermille);
void	DRV8874_forward				(DRV8874_Object *dev);
void	DRV8874_reverse				(DRV8874_Object *dev);
void	DRV8874_brake				(DRV8874_Object *dev);
void	DRV8874_coast				(DRV8874_Object *dev); 

// Current sensing
bool	DRV8874_readCurrent_mA		(DRV8874_Object *dev, uint32_t *current_mA);

// The nFAULT pin is a shared indicator, not a readable cause-specific fault register.
void	DRV8874_faultIRQHandler		(uint16_t GPIO_Pin);
bool	DRV8874_isFaultActive		(DRV8874_Object *dev);
void	DRV8874_resetFault			(DRV8874_Object *dev);

#endif // DRV8874_H_
