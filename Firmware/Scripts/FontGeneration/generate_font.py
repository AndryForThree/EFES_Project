#!/usr/bin/env python3
"""Generate one C font registry from the fonts listed in fonts.json."""

import argparse
import json
import math
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT = SCRIPT_DIR.parents[1] / "EFES_FW_HumanSide/customLibs/ST7789/Fonts"


def generate_font(spec, base_dir):
    name = spec["name"]
    size = spec["size"]
    first = spec.get("first_char", 32)
    last = spec.get("last_char", 126)
    if not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
        raise SystemExit("Font names must use uppercase C identifiers, e.g. ROBOTO_18")
    if size <= 0 or not 0 <= first <= last <= 255:
        raise SystemExit(f"Invalid size or character range for {name}")

    path = base_dir / spec["file"]
    if not path.is_file():
        raise SystemExit(f"Font non trovato: {path}")
    with path.open("rb") as font_file:
        font = ImageFont.truetype(font_file, size=size)
    chars = [chr(code) for code in range(first, last + 1)]
    boxes = [font.getbbox(char) for char in chars]

    top = min(box[1] for box in boxes)
    bottom = max(box[3] for box in boxes)
    glyphs = []
    data = []

    for char, box in zip(chars, boxes):
        width = box[2] - box[0]
        height = box[3] - box[1]
        glyphs.append({
            "offset": len(data),
            "width": width,
            "height": height,
            "advance": max(0, math.floor(font.getlength(char) + 0.5)),
            "x_offset": box[0],
            "y_offset": box[1] - top,
        })
        if width == 0 or height == 0:
            continue
        image = Image.new("L", (width, height), 0)
        ImageDraw.Draw(image).text((-box[0], -box[1]), char, font=font, fill=255)
        pixels = image.load()
        # Four-bit glyph coverage: two pixels per byte, high nibble first.
        # Preserve grayscale antialiasing instead of applying a binary threshold.
        for y in range(height):
            for x in range(0, width, 2):
                high = (pixels[x, y] * 15 + 127) // 255
                low = (pixels[x + 1, y] * 15 + 127) // 255 if x + 1 < width else 0
                data.append((high << 4) | low)

    return {
        "name": name,
        "height": max(1, bottom - top),
        "first": first,
        "last": last,
        "glyphs": glyphs,
        "data": data,
    }


def make_header(fonts):
    ids = "\n".join(f'    FONT_{font["name"]},' for font in fonts)
    return f"""/* Generated by generate_font.py. Do not edit. */
#ifndef FONTS_GENERATED_H
#define FONTS_GENERATED_H

#include <stdint.h>

typedef enum {{
{ids}
    FONT_COUNT
}} FontId;

/* Proportional glyphs: 4-bit coverage, high nibble first, byte-aligned rows.
 * Coverage 0 is background, 15 is foreground; odd-row padding is zero.
 * Offsets are relative to the pen and the top of the common font line.
 */
typedef struct {{
    uint32_t offset;
    uint16_t width;
    uint16_t height;
    uint16_t advance;
    int16_t x_offset;
    int16_t y_offset;
}} FontGlyph;

typedef struct {{
    const uint8_t *data;
    const FontGlyph *glyphs;
    uint16_t height;
    uint8_t first_char;
    uint8_t last_char;
}} FontInfo;

extern const FontInfo Fonts[FONT_COUNT];

#endif
"""


def make_source(fonts):
    lines = [
        "/* Generated by generate_font.py. Do not edit. */",
        '#include "fonts_generated.h"',
        "",
    ]
    for font in fonts:
        lines.append(f'static const uint8_t data_{font["name"]}[] = {{')
        for offset in range(0, len(font["data"]), 16):
            values = ", ".join(f"0x{value:02X}" for value in font["data"][offset:offset + 16])
            lines.append(f"    {values},")
        lines.extend(["};", ""])
        lines.append(f'static const FontGlyph glyphs_{font["name"]}[] = {{')
        for code, glyph in enumerate(font["glyphs"], start=font["first"]):
            values = ", ".join(str(glyph[key]) for key in
                               ("offset", "width", "height", "advance", "x_offset", "y_offset"))
            lines.append(f"    {{{values}}}, /* 0x{code:02X} */")
        lines.extend(["};", ""])

    lines.append("const FontInfo Fonts[FONT_COUNT] = {")
    for font in fonts:
        lines.extend([
            f'    [FONT_{font["name"]}] = {{',
            f'        .data = data_{font["name"]},',
            f'        .glyphs = glyphs_{font["name"]},',
            f'        .height = {font["height"]},',
            f'        .first_char = {font["first"]},',
            f'        .last_char = {font["last"]}',
            "    },",
        ])
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=SCRIPT_DIR / "fonts.json",
                        help="JSON file listing all fonts to generate.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="Destination directory for fonts_generated.h and .c.")
    args = parser.parse_args()

    config_path = args.config.expanduser().resolve()
    specs = json.loads(config_path.read_text(encoding="utf-8"))["fonts"]
    if not specs:
        parser.error("The configuration must contain at least one font")
    names = [spec["name"] for spec in specs]
    if len(names) != len(set(names)):
        parser.error("Each font must have a unique name")

    fonts = [generate_font(spec, config_path.parent) for spec in specs]
    output = args.output.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    (output / "fonts_generated.h").write_text(make_header(fonts), encoding="utf-8")
    (output / "fonts_generated.c").write_text(make_source(fonts), encoding="utf-8")
    print(f"Generated {output / 'fonts_generated.h'}")
    print(f"Generated {output / 'fonts_generated.c'}")
    for font in fonts:
        print(f'FONT_{font["name"]}: line height {font["height"]}, '
              f'{len(font["data"])} bitmap bytes')


if __name__ == "__main__":
    main()
